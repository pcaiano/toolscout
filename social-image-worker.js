function json(data, status = 200) {
  return new Response(JSON.stringify(data), {
    status,
    headers: { 'content-type': 'application/json; charset=utf-8', 'cache-control': 'no-store' }
  });
}

function headers(variant, model = 'flux2') {
  return {
    'content-type': 'image/jpeg',
    'cache-control': 'public, max-age=86400',
    'x-toolscout-renderer': 'flux2-editorial-v3',
    'x-toolscout-image-variant': variant,
    'x-toolscout-image-model': model
  };
}

function safe(value, max = 240) {
  return String(value || '')
    .replace(/[\r\n]+/g, ' ')
    .replace(/[^\p{L}\p{N}\s.,:;!?()&+\-/'’]/gu, '')
    .trim()
    .slice(0, max);
}

function creativeFromUrl(url, variant) {
  return {
    variant,
    concept: safe(url.searchParams.get('concept') || variant, 32),
    headline: safe(url.searchParams.get('headline') || 'Find the right tool. Faster.', 72),
    kicker: safe(url.searchParams.get('kicker') || 'ToolScout', 60),
    left: safe(url.searchParams.get('left') || '', 80),
    center: safe(url.searchParams.get('center') || '', 120),
    right: safe(url.searchParams.get('right') || '', 80),
    scene: safe(url.searchParams.get('scene') || '', 320)
  };
}

function buildPrompt(c) {
  const visualIdea = c.scene || [c.left, c.center, c.right].filter(Boolean).join(' -> ');
  return `Create a premium 1:1 social campaign image for ToolScout, an independent software discovery platform.

VISUAL IDEA
${visualIdea || c.concept}

MESSAGE
Headline: "${c.headline}"
Supporting idea: "${c.kicker}"

TOOLSCOUT BRAND DIRECTION
Contemporary, premium, restrained, authoritative tech brand. Quiet charisma, not startup hype. Dark charcoal / deep navy foundation, clean white typography, controlled electric blue and cyan accents, generous negative space, crisp geometry, subtle target/crosshair motif. Sophisticated editorial art direction suitable for a high-end B2B software brand.

IMAGE STYLE
Photorealistic premium CGI / high-end advertising photography blended with elegant information design. Realistic materials, natural cinematic lighting, strong depth, beautiful composition, subtle depth of field, highly polished commercial finish. The image must visually illustrate the idea in the post, not merely decorate it. It should feel designed by a senior art director, not generated by an AI image model.

CONTENT RULES
- Make the central visual metaphor immediately understandable.
- Use a real-world or believable digital-workspace scene when it helps communicate the idea.
- Keep the composition clean and uncluttered.
- If text appears, keep it minimal and perfectly legible. Prioritize the exact headline above; do not invent extra claims, numbers, statistics, prices, awards, customer counts or performance metrics.
- Do not invent fake software logos, fake product UI, fake testimonials or fake data.
- Do not use distorted hands, faces, icons, logos or typography.
- Do not create abstract random lines, blobs or decorative shapes with no semantic purpose.
- Avoid neon cyberpunk, glossy AI clichés, floating hologram overload, stock-photo smiles, generic robot imagery and visual AI slop.
- Do not imitate Microsoft Paint, flat clip-art or low-detail infographics.
- If a ToolScout wordmark appears, spell exactly "ToolScout". A subtle compass/target motif is acceptable, but avoid malformed logos.

FORMAT
Square 1024x1024 social image. Premium campaign quality. No border, no watermark.`;
}

function decodeBase64Image(image) {
  const binary = atob(image);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i += 1) bytes[i] = binary.charCodeAt(i);
  return bytes;
}

async function runFlux(env, model, prompt) {
  const form = new FormData();
  form.append('prompt', prompt);
  form.append('width', '1024');
  form.append('height', '1024');
  form.append('guidance', '4');
  const formResponse = new Response(form);
  const formStream = formResponse.body;
  const formContentType = formResponse.headers.get('content-type');
  return env.AI.run(model, {
    multipart: {
      body: formStream,
      contentType: formContentType
    }
  });
}

async function generate(env, prompt) {
  const attempts = [
    '@cf/black-forest-labs/flux-2-klein-9b',
    '@cf/black-forest-labs/flux-2-klein-4b'
  ];
  const errors = [];

  for (const model of attempts) {
    try {
      const result = await runFlux(env, model, prompt);
      if (result && typeof result.image === 'string' && result.image.length > 100) {
        return { bytes: decodeBase64Image(result.image), model };
      }
      errors.push(`${model}: empty image response`);
    } catch (error) {
      errors.push(`${model}: ${error?.message || String(error)}`);
    }
  }

  throw new Error(errors.join(' | '));
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const variant = safe(url.searchParams.get('variant') || 'discovery', 24).toLowerCase();

    if (url.pathname === '/health') {
      return json({
        ok: true,
        service: 'toolscout-social-image',
        renderer: 'flux2-editorial-v3',
        primary: '@cf/black-forest-labs/flux-2-klein-9b',
        fallback: '@cf/black-forest-labs/flux-2-klein-4b'
      });
    }

    if (url.pathname !== '/generate') return json({ error: 'not_found' }, 404);
    if (!['GET', 'HEAD'].includes(request.method)) return json({ error: 'method_not_allowed' }, 405);

    if (request.method === 'HEAD') {
      return new Response(null, { status: 200, headers: headers(variant) });
    }

    try {
      const creative = creativeFromUrl(url, variant);
      const prompt = buildPrompt(creative);
      const generated = await generate(env, prompt);
      return new Response(generated.bytes, {
        status: 200,
        headers: headers(variant, generated.model)
      });
    } catch (error) {
      return json({ error: 'image_generation_failed', detail: error?.message || String(error) }, 503);
    }
  }
};